export function getProductById(id: string): ProductItem | undefined {
  return CATALOG.find((p) => p.id === id);
}

export function getAllProducts(): ProductItem[] {
  return CATALOG;
}

export function getRelatedProducts(currentId: string, limit: number = 4): ProductItem[] {
  const current = CATALOG.find((p) => p.id === currentId);
  const sameBrand = CATALOG.filter((p) => p.id !== currentId && p.brand === current?.brand);
  if (sameBrand.length >= limit) return sameBrand.slice(0, limit);
  const others = CATALOG.filter((p) => p.id !== currentId && p.brand !== current?.brand);
  return [...sameBrand, ...others].slice(0, limit);
}
